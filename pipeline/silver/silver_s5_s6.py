# ============================================================
# GENERAL HELPERS
# ============================================================

def utc_now():
    return datetime.now(timezone.utc).isoformat()


def clean_output(path: Path):
    """
    Remove an existing Spark output directory so the script
    can be rerun safely during development.
    """
    if path.exists():
        shutil.rmtree(path)


def find_csv(folder: Path) -> Path:
    files = sorted(folder.glob("*.csv"))

    if not files:
        raise FileNotFoundError(
            f"No CSV file found in: {folder}"
        )

    return files[0]


def write_json(path: Path, payload: dict):
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as f:
        json.dump(
            payload,
            f,
            indent=2,
            ensure_ascii=False,
        )


def write_quality_report(
    df,
    dataset_name: str,
    quality_dir: Path,
    total_rows: int,
    clean_rows: int,
    quarantine_rows: int,
    dq_columns: list[str],
):
    """
    Write a compact Gold quality report.
    """

    quality_dir.mkdir(parents=True, exist_ok=True)

    # --------------------------------------------------------
    # Rule counts
    # --------------------------------------------------------

    rule_rows = []

    for col in dq_columns:
        failed = df.filter(F.col(col) == True).count()

        rule_rows.append(
            (
                dataset_name,
                col,
                int(failed),
                utc_now(),
            )
        )

    quality_df = df.sparkSession.createDataFrame(
        rule_rows,
        [
            "dataset",
            "rule",
            "failed_rows",
            "generated_at",
        ],
    )

    quality_output = quality_dir / "part-00000.parquet"

    clean_output(quality_dir)

    quality_df.coalesce(1).write.mode("overwrite").parquet(
        str(quality_dir)
    )

    # --------------------------------------------------------
    # Summary JSON
    # --------------------------------------------------------

    summary = {
        "dataset": dataset_name,
        "generated_at": utc_now(),
        "total_rows": int(total_rows),
        "clean_rows": int(clean_rows),
        "quarantine_rows": int(quarantine_rows),
        "quality_rules": len(dq_columns),
        "rules": {},
    }

    for row in rule_rows:
        _, rule, failed_rows, _ = row
        summary["rules"][rule] = int(failed_rows)

    summary_path = quality_dir.parent / (
        f"{dataset_name}_summary.json"
    )

    write_json(summary_path, summary)

    print()
    print("Quality report written:")
    print(f"  {quality_dir}")
    print(f"Summary:")
    print(f"  {summary_path}")


