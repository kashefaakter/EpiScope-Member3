# ============================================================

def transform_s5(spark):
    print()
    print("=" * 70)
    print("S5 FACILITIES")
    print("=" * 70)

    source = find_csv(BRONZE_S5)

    print(f"Source: {source}")

    # --------------------------------------------------------
    # Read CSV
    # --------------------------------------------------------

    df = (
        spark.read
        .option("header", True)
        .option("inferSchema", True)
        .csv(str(source))
    )

    print()
    print("Original S5 schema:")
    df.printSchema()

    print()
    print("Original S5 columns:")
    print(df.columns)

    # --------------------------------------------------------
    # Actual S5 schema generated by EpiScope generator:
    #
    # facility_id
    # district_name
    # facility_type
    # bed_capacity
    # active
    # --------------------------------------------------------

    required = [
        "facility_id",
        "district_name",
        "facility_type",
        "bed_capacity",
        "active",
    ]

    missing = [
        col for col in required
        if col not in df.columns
    ]

    if missing:
        raise ValueError(
            "Missing S5 columns: "
            + ", ".join(missing)
        )

    # --------------------------------------------------------
    # Normalize data types
    # --------------------------------------------------------

    df = (
        df
        .withColumn(
            "facility_id",
            F.trim(F.col("facility_id").cast("string"))
        )
        .withColumn(
            "district_name_source",
            F.trim(F.col("district_name").cast("string"))
        )
        .withColumn(
            "district_name",
            canonical_district_name_column(F.col("district_name_source"))
        )
        .withColumn(
            "facility_type",
            F.trim(F.col("facility_type").cast("string"))
        )
        .withColumn(
            "bed_capacity",
            F.col("bed_capacity").cast("integer")
        )
        .withColumn(
            "active",
            F.col("active").cast("boolean")
        )
    )

    # --------------------------------------------------------
    # DQ RULES
    # --------------------------------------------------------

    df = (
        df
        .withColumn(
            "dq_missing_facility_id",
            F.col("facility_id").isNull()
            | (F.col("facility_id") == "")
        )
        .withColumn(
            "dq_missing_district",
            F.col("district_name").isNull()
            | (F.col("district_name") == "")
        )
        .withColumn(
            "dq_missing_facility_type",
            F.col("facility_type").isNull()
            | (F.col("facility_type") == "")
        )
        .withColumn(
            "dq_invalid_bed_capacity",
            F.col("bed_capacity").isNull()
            | (F.col("bed_capacity") < 0)
        )
        .withColumn(
            "dq_invalid_active",
            F.col("active").isNull()
        )
    )

    # --------------------------------------------------------
    # Duplicate facility IDs
    # --------------------------------------------------------

    window_spec = Window.partitionBy("facility_id")

    df = (
        df
        .withColumn(
            "__facility_id_count",
            F.count("*").over(window_spec)
        )
        .withColumn(
            "dq_duplicate_facility_id",
            F.col("__facility_id_count") > 1
        )
    )

    # --------------------------------------------------------
    # Combined DQ reason
    # --------------------------------------------------------

    dq_columns = [
        "dq_missing_facility_id",
        "dq_missing_district",
        "dq_missing_facility_type",
        "dq_invalid_bed_capacity",
        "dq_invalid_active",
        "dq_duplicate_facility_id",
    ]

    reason_parts = []

    for col in dq_columns:
        reason_parts.append(
            F.when(
                F.col(col),
                F.lit(col.replace("dq_", ""))
            )
        )

    df = df.withColumn(
        "dq_reason",
        F.concat_ws(
            "; ",
            *reason_parts
        )
    )

    # --------------------------------------------------------
    # Clean / quarantine
    # --------------------------------------------------------

    quarantine = df.filter(F.col("dq_reason") != "")

    clean = df.filter(F.col("dq_reason") == "")

    # --------------------------------------------------------
    # Remove helper columns from final outputs
    # --------------------------------------------------------

    helper_columns = (
        dq_columns
        + ["__facility_id_count"]
    )

    quarantine = quarantine.drop(*helper_columns)

    clean = clean.drop(*helper_columns)

    # --------------------------------------------------------
    # Metadata
    # --------------------------------------------------------

    clean = (
        clean
        .withColumn(
            "_silver_processed_at",
            F.current_timestamp()
        )
        .withColumn(
            "_source_dataset",
            F.lit("S5_facilities")
        )
    )

    quarantine = (
        quarantine
        .withColumn(
            "_silver_processed_at",
            F.current_timestamp()
        )
        .withColumn(
            "_source_dataset",
            F.lit("S5_facilities")
        )
    )

    # --------------------------------------------------------
    # Counts
    # --------------------------------------------------------

    total_rows = df.count()
    clean_rows = clean.count()
    quarantine_rows = quarantine.count()

    print()
    print("S5 statistics:")
    print(f"  Total rows      : {total_rows:,}")
    print(f"  Clean rows      : {clean_rows:,}")
    print(f"  Quarantine rows : {quarantine_rows:,}")

    # --------------------------------------------------------
    # Write Silver
    # --------------------------------------------------------

    clean_output(SILVER_S5)
    clean_output(QUARANTINE_S5)

    (
        clean
        .coalesce(1)
        .write
        .mode("overwrite")
        .parquet(str(SILVER_S5))
    )

    (
        quarantine
        .coalesce(1)
        .write
        .mode("overwrite")
        .parquet(str(QUARANTINE_S5))
    )

    print()
    print("S5 Silver written:")
    print(f"  {SILVER_S5}")

    print("S5 quarantine written:")
    print(f"  {QUARANTINE_S5}")

    # --------------------------------------------------------
    # Quality report
    # --------------------------------------------------------

    write_quality_report(
        df=df,
        dataset_name="s5_facilities",
        quality_dir=QUALITY_S5,
        total_rows=total_rows,
        clean_rows=clean_rows,
        quarantine_rows=quarantine_rows,
        dq_columns=dq_columns,
    )


