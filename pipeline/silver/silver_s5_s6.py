def transform_s6(spark):
    print()
    print("=" * 70)
    print("S6 STOCK + BEDS")
    print("=" * 70)

    source = find_csv(BRONZE_S6)

    print(f"Source: {source}")

    # --------------------------------------------------------
    # Read CSV
    # --------------------------------------------------------

    df = (
        spark.read
        .option("header", True)
        .option("inferSchema", True)
        .csv(str(source))
    )

    print()
    print("Original S6 schema:")
    df.printSchema()

    print()
    print("Original S6 columns:")
    print(df.columns)

    required = [
        "snapshot_date",
        "facility_id",
        "district_name",
        "bed_capacity",
        "available_beds",
        "occupied_beds",
        "saline_stock",
        "test_kit_stock",
    ]

    missing = [
        col for col in required
        if col not in df.columns
    ]

    if missing:
        raise ValueError(
            "Missing S6 columns: "
            + ", ".join(missing)
        )

    # --------------------------------------------------------
    # Normalize types
    # --------------------------------------------------------

    df = (
        df
        .withColumn(
            "snapshot_date",
            F.to_date(F.col("snapshot_date"))
        )
        .withColumn(
            "facility_id",
            F.trim(F.col("facility_id").cast("string"))
        )
        .withColumn(
            "district_name_source",
            F.trim(F.col("district_name").cast("string"))
        )
        .withColumn(
            "district_name",
            canonical_district_name_column(F.col("district_name_source"))
        )
        .withColumn(
            "bed_capacity",
            F.col("bed_capacity").cast("integer")
        )
        .withColumn(
            "available_beds",
            F.col("available_beds").cast("integer")
        )
        .withColumn(
            "occupied_beds",
            F.col("occupied_beds").cast("integer")
        )
        .withColumn(
            "saline_stock",
            F.col("saline_stock").cast("integer")
        )
        .withColumn(
            "test_kit_stock",
            F.col("test_kit_stock").cast("integer")
        )
    )

    # --------------------------------------------------------
    # DQ RULES
    # --------------------------------------------------------

    df = (
        df
        .withColumn(
            "dq_missing_snapshot_date",
            F.col("snapshot_date").isNull()
        )
        .withColumn(
            "dq_missing_facility_id",
            F.col("facility_id").isNull()
            | (F.col("facility_id") == "")
        )
        .withColumn(
            "dq_missing_district",
            F.col("district_name").isNull()
            | (F.col("district_name") == "")
        )
        .withColumn(
            "dq_invalid_bed_capacity",
            F.col("bed_capacity").isNull()
            | (F.col("bed_capacity") < 0)
        )
        .withColumn(
            "dq_invalid_available_beds",
            F.col("available_beds").isNull()
            | (F.col("available_beds") < 0)
            | (
                F.col("bed_capacity").isNotNull()
                & (
                    F.col("available_beds")
                    > F.col("bed_capacity")
                )
            )
        )
        .withColumn(
            "dq_invalid_occupied_beds",
            F.col("occupied_beds").isNull()
            | (F.col("occupied_beds") < 0)
            | (
                F.col("bed_capacity").isNotNull()
                & (
                    F.col("occupied_beds")
                    > F.col("bed_capacity")
                )
            )
        )
        .withColumn(
            "dq_invalid_saline_stock",
            F.col("saline_stock").isNull()
            | (F.col("saline_stock") < 0)
        )
        .withColumn(
            "dq_invalid_test_kit_stock",
            F.col("test_kit_stock").isNull()
            | (F.col("test_kit_stock") < 0)
        )
    )

    dq_columns = [
        "dq_missing_snapshot_date",
        "dq_missing_facility_id",
        "dq_missing_district",
        "dq_invalid_bed_capacity",
        "dq_invalid_available_beds",
        "dq_invalid_occupied_beds",
        "dq_invalid_saline_stock",
        "dq_invalid_test_kit_stock",
    ]

    # --------------------------------------------------------
    # Combined DQ reason
    # --------------------------------------------------------

    reason_parts = []

    for col in dq_columns:
        reason_parts.append(
            F.when(
                F.col(col),
                F.lit(col.replace("dq_", ""))
            )
        )

    df = df.withColumn(
        "dq_reason",
        F.concat_ws(
            "; ",
            *reason_parts
        )
    )

    # --------------------------------------------------------
    # Clean / quarantine
    # --------------------------------------------------------

    quarantine = df.filter(F.col("dq_reason") != "")

    clean = df.filter(F.col("dq_reason") == "")

    quarantine = quarantine.drop(*dq_columns)

    clean = clean.drop(*dq_columns)

    # --------------------------------------------------------
    # Metadata
    # --------------------------------------------------------

    clean = (
        clean
        .withColumn(
            "_silver_processed_at",
            F.current_timestamp()
        )
        .withColumn(
            "_source_dataset",
            F.lit("S6_stock_beds")
        )
    )

    quarantine = (
        quarantine
        .withColumn(
            "_silver_processed_at",
            F.current_timestamp()
        )
        .withColumn(
            "_source_dataset",
            F.lit("S6_stock_beds")
        )
    )

    # --------------------------------------------------------
    # Counts
    # --------------------------------------------------------

    total_rows = df.count()
    clean_rows = clean.count()
    quarantine_rows = quarantine.count()

    print()
    print("S6 statistics:")
    print(f"  Total rows      : {total_rows:,}")
    print(f"  Clean rows      : {clean_rows:,}")
    print(f"  Quarantine rows : {quarantine_rows:,}")

    # --------------------------------------------------------
    # Write Silver
    # --------------------------------------------------------

    clean_output(SILVER_S6)
    clean_output(QUARANTINE_S6)

    (
        clean
        .write
        .mode("overwrite")
        .partitionBy("snapshot_date")
        .parquet(str(SILVER_S6))
    )

    (
        quarantine
        .write
        .mode("overwrite")
        .parquet(str(QUARANTINE_S6))
    )

    print()
    print("S6 Silver written:")
    print(f"  {SILVER_S6}")

    print("S6 quarantine written:")
    print(f"  {QUARANTINE_S6}")

    # --------------------------------------------------------
    # Quality report
    # --------------------------------------------------------

    write_quality_report(
        df=df,
        dataset_name="s6_stock_beds",
        quality_dir=QUALITY_S6,
        total_rows=total_rows,
        clean_rows=clean_rows,
        quarantine_rows=quarantine_rows,
        dq_columns=dq_columns,
    )


# ============================================================
# MAIN
# ============================================================

def main():

    print("=" * 70)
    print("EpiScope - S5 + S6 Silver Transformation")
    print("=" * 70)

    spark = (
        SparkSession.builder
        .appName("EpiScope-S5-S6-Silver")
        .master("local[*]")
        .config(
            "spark.sql.adaptive.enabled",
            "true"
        )
        .config(
            "spark.sql.shuffle.partitions",
            "8"
        )
        .config(
            "spark.driver.memory",
            "4g"
        )
        .getOrCreate()
    )

    spark.sparkContext.setLogLevel("WARN")

    try:

        transform_s5(spark)

        transform_s6(spark)

        print()
        print("=" * 70)
        print("S5 + S6 SILVER TRANSFORMATION COMPLETED")
        print("=" * 70)

    finally:
        spark.stop()


if __name__ == "__main__":
    main()